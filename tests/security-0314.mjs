import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {ReadableStream} from 'node:stream/web';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=fs.readFileSync(path.join(root,'background.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
assert.equal(manifest.version,'0.3.18');
const extract=(start,end)=>source.slice(source.indexOf(start),source.indexOf(end,source.indexOf(start)));
const originFns=extract('const CAIXOTA_EXTENSION_PAGES','chrome.runtime.onMessage.addListener((message,sender,sendResponse)=>');
const context=vm.createContext({URL,Set,Number,chrome:{runtime:{id:'abc',getURL:p=>'chrome-extension://abc/'+p.replace(/^\//,'')}}});
vm.runInContext(originFns,context);
const isAllowed=(type,sender)=>vm.runInContext('allowCaixotaMessage',context)(type,sender);
const panel={id:'abc',url:'chrome-extension://abc/panel.html',tab:{id:1},frameId:0};
const workbench={id:'abc',url:'chrome-extension://abc/workbench.html',tab:{id:1},frameId:2};
const content={id:'abc',url:'https://example.com/path',tab:{id:22},frameId:0};
assert.equal(isAllowed('GET_SETTINGS',panel),true);
assert.equal(isAllowed('GET_SETTINGS',content),false);
assert.equal(isAllowed('UNLOCK_PASSWORD_VAULT',content),true);
assert.equal(isAllowed('UNLOCK_PASSWORD_VAULT',panel),false);
assert.equal(isAllowed('RECORD_TOOL_USAGE',workbench),true);
assert.equal(isAllowed('CAPTURE_VISIBLE_TAB',{...content,frameId:1}),false);
assert.equal(isAllowed('CREATE_PASSWORD_VAULT',{...content,id:'other-extension'}),false);
const envelopeSource=extract('function isPasswordVaultEnvelope','async function encryptPasswordEntries');
vm.runInContext(envelopeSource,context);
const valid=vm.runInContext('isPasswordVaultEnvelope',context);
const row={version:1,iterations:310000,salt:'a'.repeat(24),iv:'b'.repeat(16),ciphertext:'c'.repeat(24)};
assert.equal(valid(row),true);
assert.equal(valid({...row,iterations:1e9}),false);
assert.equal(valid({...row,iv:'%%%'}),false);
assert.equal(valid({...row,ciphertext:'x'.repeat(1024*1024+4)}),false);
const zip=fs.readFileSync(path.join(root,'assets/module-package.mjs'),'utf8');
assert(zip.includes('totalBytes>MAX_MANIFEST'));
assert(!zip.includes('new Response(stream).arrayBuffer()'));
const images=extract('const MAX_IMAGE_DOWNLOAD_BYTES','function uint8ToBase64');
const imageContext=vm.createContext({URL,Uint8Array,AbortController,TextDecoder,ReadableStream,setTimeout,clearTimeout,btoa,console,fetch:async(url)=>({url,ok:true,headers:new Headers({'content-type':'image/png'}),body:new ReadableStream({start(ctrl){ctrl.enqueue(new Uint8Array(20*1024*1024+1));ctrl.close();}})}),Headers});
vm.runInContext(images,imageContext);
await assert.rejects(()=>vm.runInContext("fetchImageData('https://example.com/image.png')",imageContext),/20 MB/);
await assert.rejects(()=>vm.runInContext("fetchImageData('file:///etc/passwd')",imageContext),/HTTP\(S\)/);
console.log('OK 0.3.14: origem de mensagens, envelope do cofre, download limitado e ZIP limitado.');
