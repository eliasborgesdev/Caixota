import assert from 'node:assert/strict';
import fs from 'node:fs';
import {webcrypto} from 'node:crypto';
import {SHORTCUT_KEY,normalizeChord,chordFromEvent,safeSiteUrl,cleanShortcuts} from '../assets/site-shortcuts.mjs';
import {mathTemplates} from '../assets/math-generator.mjs';
assert.equal(normalizeChord('ctrl+shift+l'),'Ctrl+Shift+L');
assert.equal(normalizeChord('Alt+F5'),'Alt+F5');
assert.equal(chordFromEvent({ctrlKey:true,altKey:false,shiftKey:true,metaKey:false,key:'L',code:'KeyL'}),'Ctrl+Shift+L');
assert.equal(safeSiteUrl('example.com'),'https://example.com/');
assert.equal(safeSiteUrl('javascript:alert(1)'),'');
assert.equal(safeSiteUrl('file:///private'),'');
const entries=cleanShortcuts([{url:'https://a.test',chord:'Ctrl+Shift+L'},{url:'https://b.test',chord:'Ctrl+Shift+L'},{url:'javascript:console.log(1)',chord:'Ctrl+Shift+L'}]);
assert.equal(entries.length,2);assert.equal(entries[0].chord,entries[1].chord);
const v={a:1,b:-5,c:6,p:3};
assert.match(mathTemplates.quadratic.make(v).answer,/x₁ = 3, x₂ = 2/);
assert.equal(mathTemplates.linear.make({a:3,b:4,c:16}).answer,'x = 4');
assert.equal(mathTemplates.derivative.make({a:3,b:2,c:1}).answer,"f'(x) = 6x + 2");
assert.equal(mathTemplates.limit.make(v).answer,'0');
assert.throws(()=>mathTemplates.linear.make({a:0,b:2,c:3}),/não pode ser zero/);
